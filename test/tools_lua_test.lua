local console = require("console")
local lua_exec = require("tools.lua_exec")
local fake_console = require("fake_console")
local h = require("helpers")

local function setup(enabled)
  local fake = fake_console.new()
  local c = console.new(fake.api)
  local tools, ctx = {}, { budget_ms = 10000, lua_enabled = function() return enabled end }
  lua_exec.register(tools, c, ctx, { ObjectList = fake.api.ObjectList, Echo = fake.api.Echo, Printf = fake.api.Printf })
  return fake, tools, ctx
end

h.describe("ma3_lua refused when off", function()
  local _, tools, ctx = setup(false)
  local r, err = tools.ma3_lua.handler({ code = "return 1" }, ctx)
  h.eq(r, nil); h.truthy(err:find("Lua execution is off"))
end)

h.describe("ma3_lua returns values and captured output", function()
  local fake, tools, ctx = setup(true)
  local r = tools.ma3_lua.handler({ code = "Echo('x') Printf('y %d', 2) return 1+1" }, ctx)
  h.eq(r.returned, 2); h.eq(r.output[1], "x"); h.eq(r.output[2], "y 2")
  local r2 = tools.ma3_lua.handler({ code = "return {a=1, b={2,3}}" }, ctx)
  h.eq(r2.returned.a, 1); h.eq(r2.returned.b[2], 3)
  local r3 = tools.ma3_lua.handler({ code = "return ObjectList('Sequence 12')[1].name" }, ctx)
  h.eq(r3.returned, "Song A")
  local r4 = tools.ma3_lua.handler({ code = "return ObjectList('Sequence 12')[1]" }, ctx)
  h.eq(r4.returned, "Sequence 12", "handles come back as addresses")
end)

h.describe("ma3_lua sandbox", function()
  local _, tools, ctx = setup(true)
  local r, err = tools.ma3_lua.handler({ code = "return os.execute('ls')" }, ctx)
  h.eq(r, nil); h.truthy(err:find("nil value"), err)
  r, err = tools.ma3_lua.handler({ code = "return io" }, ctx)
  h.eq(r.returned, nil, "io is nil")
  r, err = tools.ma3_lua.handler({ code = "return os.exit" }, ctx)
  h.eq(r.returned, nil)
  r = tools.ma3_lua.handler({ code = "return os.time() > 0, os.date ~= nil" }, ctx)
  h.eq(r.returned, true, "os.time still works")
  r, err = tools.ma3_lua.handler({ code = "this is not lua" }, ctx)
  h.eq(r, nil); h.truthy(err:find("syntax"), err)
  r, err = tools.ma3_lua.handler({ code = "error('boom')" }, ctx)
  h.eq(r, nil); h.truthy(err:find("boom"))
  r, err = tools.ma3_lua.handler({}, ctx)
  h.eq(r, nil); h.truthy(err:find("code"))
end)

h.describe("ma3_lua deadline", function()
  local fake, tools, ctx = setup(true)
  fake.slow = true   -- the fake clock advances only when asked; the hook asks on every count
  local r, err = tools.ma3_lua.handler({ code = "while true do end", timeout_ms = 50 }, ctx)
  h.eq(r, nil); h.truthy(err:find("deadline"), err)
  local r2 = tools.ma3_lua.handler({ code = "return 'still works'" }, ctx)
  h.eq(r2.returned, "still works", "hook removed afterwards")
end)
