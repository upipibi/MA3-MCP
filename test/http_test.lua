local http = require("http")
local h = require("helpers")

h.describe("http.parse complete request", function()
  local raw = "POST /mcp HTTP/1.1\r\nHost: x\r\ncontent-length: 2\r\nMcp-Method: ping\r\n\r\n{}"
  local req, st, n = http.parse(raw)
  h.eq(st, "ok")
  h.eq(req.method, "POST")
  h.eq(req.path, "/mcp")
  h.eq(req.version, "1.1")
  h.eq(req.body, "{}")
  h.eq(req.headers["mcp-method"], "ping")
  h.eq(http.header(req, "MCP-METHOD"), "ping")
  h.eq(n, #raw)
end)

h.describe("http.parse needs more", function()
  local _, st2 = http.parse("POST /mcp HTTP/1.1\r\ncontent-length: 5\r\n\r\n{}")
  h.eq(st2, "need_more", "short body")
  local _, st3 = http.parse("POST /mcp HTTP/1.1\r\ncontent-len")
  h.eq(st3, "need_more", "partial headers")
  local _, st0 = http.parse("")
  h.eq(st0, "need_more", "empty")
end)

h.describe("http.parse bad and too large", function()
  local _, st4 = http.parse("GARBAGE\r\n\r\n")
  h.eq(st4, "bad")
  local _, st5 = http.parse("POST /mcp HTTP/1.1\r\ncontent-length: 2000000\r\n\r\n")
  h.eq(st5, "too_large")
  local _, st6 = http.parse("POST /mcp HTTP/1.1\r\ntransfer-encoding: chunked\r\n\r\n")
  h.eq(st6, "bad", "chunked refused")
  local _, st7 = http.parse(string.rep("A", 17000) .. "\r\n\r\n")
  h.eq(st7, "too_large", "header block over 16 KB")
end)

h.describe("http.parse GET with query and trailing data", function()
  local raw = "GET /mcp?x=1 HTTP/1.1\r\n\r\n"
  local r, st, n = http.parse(raw .. "NEXT")
  h.eq(st, "ok")
  h.eq(r.query, "x=1")
  h.eq(r.path, "/mcp")
  h.eq(r.body, "")
  h.eq(n, #raw, "consumed only the first request")
end)

h.describe("http.response", function()
  local s = http.response(405, {Allow = "POST"}, "")
  h.truthy(s:find("^HTTP/1.1 405 Method Not Allowed\r\n"))
  h.truthy(s:find("\r\nContent%-Length: 0\r\n"))
  h.truthy(s:find("\r\nAllow: POST\r\n"))
  h.truthy(s:find("\r\nConnection: close\r\n"))
  h.truthy(s:find("\r\nDate: "))
  h.truthy(s:find("\r\n\r\n$"))
  local j = http.response(200, {["Content-Type"] = "application/json"}, '{"a":1}')
  h.truthy(j:find("\r\nContent%-Length: 7\r\n"))
  h.truthy(j:find('\r\n\r\n{"a":1}$'))
  h.eq(http.STATUS_TEXT[202], "Accepted")
end)
