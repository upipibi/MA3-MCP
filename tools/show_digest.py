#!/usr/bin/env python3
"""Turn MA3 MCP bulk dumps (fixtures/groups/sequences/pages JSON) into a per-show Markdown report.

usage: show_digest.py <dir-with-json> <show title> <out.md>
Prints a compact digest to stdout; writes the full report to out.md.
"""
import json, sys, re, collections, pathlib

d, title, out = pathlib.Path(sys.argv[1]), sys.argv[2], pathlib.Path(sys.argv[3])
def load(n):
    p = d / f"{n}.json"
    return json.load(open(p)) if p.exists() else None

fx, gr, sq, pg = load("fixtures"), load("groups"), load("sequences"), load("pages")
rep, dig = [], []
def R(s=""): rep.append(s)
def D(s=""): dig.append(s)
def both(s=""): rep.append(s); dig.append(s)

both(f"# Show digest: {title}")
R(f"\nGenerated by tools/show_digest.py from MA3 MCP bulk reads. Raw JSON kept out of the repo.\n")

# ---------- fixtures ----------
if fx:
    rows = fx["rows"]
    flat = []
    def walk(r, depth, parent):
        flat.append((r, depth, parent))
        for ch in r.get("children") or []:
            walk(ch, depth + 1, r)
    for r in rows: walk(r, 0, None)
    both(f"\n## Fixtures: {len(rows)} top-level entries, {len(flat)} nodes, {len(fx.get('fixture_types', []))} fixture types")
    R("\n### Top-level patch entries\n")
    R("| ID | Name | Type | Mode | Patch | Children |")
    R("| --- | --- | --- | --- | --- | --- |")
    for r in rows:
        R(f"| {r.get('id','')} | {r.get('name','')} | {r.get('fixture_type','')} | {r.get('mode','')} | {r.get('patch','')} | {len(r.get('children') or [])} |")
    # by type over all nodes with an id
    bytype = collections.defaultdict(list)
    for r, depth, parent in flat:
        if r.get("idtype") in (None, "", "Fixture", "Generic") or True:
            bytype[(r.get("fixture_type",""), r.get("idtype",""))].append(r)
    both("\n### By fixture type (all nodes)\n")
    both("| Type | ID type | Count | IDs (min–max) | Universes | Name examples |")
    both("| --- | --- | --- | --- | --- | --- |")
    def idnum(r):
        try: return int(str(r.get("id","")).split(".")[0])
        except: return None
    for (t, it), lst in sorted(bytype.items(), key=lambda kv: (-len(kv[1]), kv[0])):
        ids = [i for i in (idnum(r) for r in lst) if i is not None]
        unis = sorted({p.split(".")[0] for p in (r.get("patch") or "" for r in lst) if p})
        names = []
        for r in lst:
            n = r.get("name","")
            if n and n not in names: names.append(n)
            if len(names) >= 4: break
        rng = f"{min(ids)}–{max(ids)}" if ids else ""
        both(f"| {t} | {it} | {len(lst)} | {rng} | {', '.join(unis)} | {'; '.join(names)} |")
    R("\n### Every fixture with an ID and a patch\n")
    R("| ID | CID | Name | Type | Mode | Patch |")
    R("| --- | --- | --- | --- | --- | --- |")
    for r, depth, parent in flat:
        if r.get("patch") or r.get("id"):
            R(f"| {r.get('id','')} | {r.get('cid','')} | {r.get('name','')} | {r.get('fixture_type','')} | {r.get('mode','')} | {r.get('patch','')} |")

# ---------- groups ----------
if gr:
    rows = gr["rows"]
    both(f"\n## Groups: {len(rows)}")
    both("\n| No | Name | Members | Grid (x range × y range) | Appearance |")
    both("| --- | --- | --- | --- | --- |")
    for r in rows:
        md = r.get("member_details") or []
        xs = [m.get("x",0) for m in md]; ys = [m.get("y",0) for m in md]
        grid = f"x {min(xs)}–{max(xs)}, y {min(ys)}–{max(ys)}" if md else ""
        both(f"| {r['no']} | {r['name']} | {r.get('member_count', len(r.get('members',[])))} | {grid} | {r.get('appearance','')} |")
    R("\n### Group members (subfixture indices)\n")
    for r in rows:
        R(f"- **{r['no']} {r['name']}** ({r.get('member_count')}): {', '.join(r.get('members', []))}")

# ---------- sequences ----------
if sq:
    rows = sq["rows"]
    both(f"\n## Sequences: {len(rows)}")
    both("\n| No | Name | Cues | First cue | Last cue | On executors |")
    both("| --- | --- | --- | --- | --- | --- |")
    for r in rows:
        ex = "; ".join(f"p{e['page']} {e['page_name']} x{e['executor']}" for e in r.get("executors", []))
        both(f"| {r['no']} | {r['name']} | {r['cue_count']} | {r.get('first_cue','')} | {r.get('last_cue','')} | {ex} |")
    # song cue detail
    songs = [r for r in rows if r.get("cue_count", 0) >= 2]
    R(f"\n### Cue lists of the {len(songs)} sequences with 2 or more cues (cue numbers are console-internal thousandths: 1000 = Cue 1, 12200 = Cue 12.2)\n")
    vocab = collections.Counter(); trig = collections.Counter(); steps = collections.Counter()
    for r in songs:
        cues = r.get("cues") or []
        R(f"\n#### Sequence {r['no']} {r['name']} ({r['cue_count']} cues)\n")
        R("| Cue | Name | Trigger |")
        R("| --- | --- | --- |")
        prev = None
        for cue in cues:
            R(f"| {cue['no']} | {cue['name']} | {cue['trigger']} |")
            base = re.sub(r"\s*\d+\s*$", "", cue["name"]).strip()
            vocab[base] += 1; trig[cue["trigger"]] += 1
            if prev is not None and isinstance(cue["no"], (int, float)):
                steps[cue["no"] - prev] += 1
            prev = cue["no"] if isinstance(cue["no"], (int, float)) else prev
    both(f"\n### Cue vocabulary across those {len(songs)} sequences (name with trailing number stripped)\n")
    both("| Cue name | Uses |")
    both("| --- | --- |")
    for name, n in vocab.most_common(60):
        both(f"| {name} | {n} |")
    both("\n### Triggers\n")
    for t, n in trig.most_common(): both(f"- {t}: {n}")
    both("\n### Cue number steps (next minus previous)\n")
    for s, n in sorted(steps.items(), key=lambda kv: -kv[1])[:12]: both(f"- {s}: {n}")

# ---------- pages ----------
if pg:
    rows = pg["rows"]
    both(f"\n## Pages: {len(rows)}")
    both("\n| Page | Name | Executors assigned |")
    both("| --- | --- | --- |")
    for r in rows:
        both(f"| {r['no']} | {r['name']} | {len([e for e in r['executors'] if e.get('assigned')])} |")
    for r in rows:
        R(f"\n### Page {r['no']} {r['name']}\n")
        R("| Exec | Label | Assigned | Key | Fader | W×H |")
        R("| --- | --- | --- | --- | --- | --- |")
        for e in r["executors"]:
            R(f"| {e['executor']} | {e.get('label','')} | {e.get('assigned','')} | {e.get('key','')} | {e.get('fader','')} | {e.get('width','')}×{e.get('height','')} |")
    # digest: song row of each weekend-looking page
    D("\n### Executors 101–120 per page (the song row)\n")
    for r in rows:
        row = [f"{e['executor']}={e.get('label','')}" for e in r["executors"] if 101 <= e["executor"] <= 120 and e.get("assigned")]
        if row: D(f"- p{r['no']} {r['name']}: " + ", ".join(row))

out.parent.mkdir(parents=True, exist_ok=True)
out.write_text("\n".join(rep) + "\n")
print("\n".join(dig))
print(f"\n[report written: {out}, {len(rep)} lines]")
