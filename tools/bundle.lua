-- Bundles src/**.lua into one plugin file: each module becomes a package.preload entry,
-- then the entry hands the plugin arguments to main.entry.
local out_path = arg[1] or "dist/MA3 MCP.lua"

local modules = {
  "http", "mcp", "server", "auth", "settings", "console", "log", "addr",
  "tools.generic", "tools.bulk", "tools.show", "tools.lua_exec", "ui", "main",
}

local function read(path)
  local f = io.open(path, "r")
  if not f then return nil end
  local d = f:read("a")
  f:close()
  return d
end

local parts = {}
parts[#parts + 1] = "-- MA3 MCP plugin bundle. Generated by tools/bundle.lua; do not edit by hand.\n"
parts[#parts + 1] = "local __plugin_args = table.pack(...)\n"
for _, name in ipairs(modules) do
  local src = read("src/" .. name:gsub("%.", "/") .. ".lua")
  if src then
    parts[#parts + 1] = string.format("package.preload[%q] = function(...)\n%s\nend\n", name, src)
  end
end
parts[#parts + 1] = "local __main = require(\"main\")\n"
parts[#parts + 1] = "return __main.entry(__plugin_args[1], __plugin_args[2], __plugin_args[3], __plugin_args[4])\n"

local f = assert(io.open(out_path, "w"))
f:write(table.concat(parts))
f:close()
print("wrote " .. out_path)
