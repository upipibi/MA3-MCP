-- Bundles src/**.lua into one plugin file. The console's package.loaded is shared by every
-- plugin and already holds modules such as "http" (LuaSocket), so the bundle never touches
-- package.*: each module runs with its own require shim that resolves bundled names first
-- and hands anything else (socket, json, lfs) to the console's require.
local out_path = arg[1] or "dist/MA3 MCP.lua"

local modules = {
  "http", "mcp", "server", "auth", "settings", "console", "log", "addr",
  "tools.generic", "tools.bulk", "tools.show", "tools.lua_exec", "ui", "main",
}

local function read(path)
  local f = io.open(path, "r")
  if not f then return nil end
  local d = f:read("a")
  f:close()
  return d
end

local parts = {}
parts[#parts + 1] = [[
-- MA3 MCP plugin bundle. Generated by tools/bundle.lua; do not edit by hand.
local __plugin_args = table.pack(...)
local __host_require = require
local __sources, __loaded = {}, {}
local function __require(name)
  local m = __loaded[name]
  if m ~= nil then return m end
  local src = __sources[name]
  if src == nil then return __host_require(name) end
  local env = setmetatable({ require = __require }, { __index = _G })
  local chunk, err = load(src, "=ma3mcp/" .. name, "t", env)
  if not chunk then error("MA3 MCP: cannot load module " .. name .. ": " .. tostring(err)) end
  m = chunk(name)
  if m == nil then m = true end
  __loaded[name] = m
  return m
end
]]
for _, name in ipairs(modules) do
  local src = read("src/" .. name:gsub("%.", "/") .. ".lua")
  if src then
    -- long-bracket level chosen so the source cannot terminate it early
    local level = 1
    while src:find("%]" .. string.rep("=", level) .. "%]") do level = level + 1 end
    local eq = string.rep("=", level)
    parts[#parts + 1] = string.format("__sources[%q] = [%s[\n%s]%s]\n", name, eq, src, eq)
  end
end
parts[#parts + 1] = [[
-- Load guard: a failure here would otherwise be silent. It is written to the temp folder
-- and echoed, and the pool button then reports it instead of doing nothing.
local __ok, __main_or_err, __cleanup = pcall(function()
  local m = __require("main")
  return m.entry(__plugin_args[1], __plugin_args[2], __plugin_args[3], __plugin_args[4])
end)
pcall(function()
  local f = io.open(GetPath(Enums.PathType.Temp) .. "/ma3_mcp_load.txt", "w")
  if f then f:write(os.date("%Y-%m-%d %H:%M:%S"), " ", __ok and "loaded" or ("FAILED: " .. tostring(__main_or_err)), "\n") f:close() end
end)
if not __ok then
  local __msg = "MA3 MCP failed to load: " .. tostring(__main_or_err)
  pcall(function()
    local f = io.open(GetPath(Enums.PathType.Temp) .. "/ma3_mcp_load_error.txt", "w")
    if f then f:write(__msg, "\n") f:close() end
  end)
  pcall(function() ErrPrintf(__msg) end)
  return function() pcall(function() ErrPrintf(__msg) end) end
end
return __main_or_err, __cleanup
]]

local f = assert(io.open(out_path, "w"))
f:write(table.concat(parts))
f:close()
print("wrote " .. out_path)
