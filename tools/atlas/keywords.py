#!/usr/bin/env python3
"""Write docs/atlas/topics/keywords.md: every command keyword and option keyword from the
downloaded MA help, with its shortcut, its help page id (MA's text is not copied), the topic pages that mention it,
and how ma3_command treats it (refused, or /NoConfirmation added).

usage: python3 -I tools/atlas/keywords.py [--ver 2.5]
Needs .cache/ma-help/<ver>/html (tools/helpsite/fetch.py). Reads src/tools/generic.lua for the
plugin's rules so the table never drifts from the code."""
import html, os, re, sys

args = sys.argv[1:]
ver = args[args.index("--ver") + 1] if "--ver" in args else "2.5"
here = os.path.dirname(os.path.abspath(__file__))
repo = os.path.abspath(os.path.join(here, "..", ".."))
hroot = os.path.join(repo, ".cache", "ma-help", ver, "html")
topics = os.path.join(repo, "docs", "atlas", "topics")


def page_text(pid):
    s = open(os.path.join(hroot, pid + ".html"), encoding="utf-8", errors="replace").read()
    i = s.find('class="topic-content"')
    b = s[i:] if i >= 0 else s
    for stop in ('class="CHSeeAlso', 'id="pnlFooter"'):
        j = b.find(stop)
        if j > 0:
            b = b[:j]
    b = re.sub(r"<script.*?</script>|<style.*?</style>", "", b, flags=re.S)
    b = re.sub(r"<(br|/p|/li|/h\d|/tr|/div|/pre)[^>]*>", "\n", b)
    b = re.sub(r"<h(\d)[^>]*>", lambda m: "\n" + "#" * int(m.group(1)) + " ", b)
    t = html.unescape(re.sub(r"<[^>]+>", "", b)).replace("\xa0", " ")
    t = re.sub(r"[ \t]+", " ", t)
    return [l.strip() for l in t.split("\n") if l.strip()]


def title_of(pid):
    s = open(os.path.join(hroot, pid + ".html"), encoding="utf-8", errors="replace").read()
    m = re.search(r"<title>(.*?)</title>", s, re.S)
    t = html.unescape(m.group(1)).strip() if m else pid
    t = t.split("»")[-1].split("|")[0].strip()
    return re.sub(r"\s+(Option )?Keyword$", "", t)


def describe(lines):
    shortcut, desc = "", ""
    for l in lines:
        m = re.search(r"shortcuts? (\S+)", l)
        if m and not shortcut and "Type the shortcut" in l:
            shortcut = m.group(1).rstrip(".;,")
    for i, l in enumerate(lines):
        if l.lstrip("# ").lower() == "description":
            for k in lines[i + 1:i + 6]:
                if not k.startswith("#") and len(k) > 12 and not k.startswith("Hint") and not k.startswith("Important"):
                    desc = k
                    break
            break
    if not desc:
        for l in lines:
            if len(l) > 30 and "User Manual" not in l and "Version 2" not in l and not l.startswith("To enter"):
                desc = l
                break
    desc = re.sub(r"^(The|This) \S+ (option )?keyword (is (a|an) )?", "", desc).strip()
    return shortcut, desc[:140].replace("|", "/")


# The plugin's rules, read from the code.
gen = open(os.path.join(repo, "src", "tools", "generic.lua"), encoding="utf-8").read()
refused = dict(re.findall(r'^\s*\{ "([a-z0-9]+)", "[a-z0-9]+", .*"((?:refused|use )[^"]*)" \},\s*$', gen, re.M))
noconf = re.search(r"NOCONFIRM_PREFIXES = \{([^}]*)\}", gen)
noconf = set(re.findall(r'"([a-z]+)"', noconf.group(1))) if noconf else set()

# Topic pages and the words they mention in backticks.
mentions = {}
for f in sorted(os.listdir(topics)):
    if not f.endswith(".md") or f in ("INDEX.md", "keywords.md"):
        continue
    text = open(os.path.join(topics, f), encoding="utf-8").read()
    words = set()
    fences = re.findall(r"```.*?\n(.*?)```", text, re.S)
    text = re.sub(r"```.*?```", "", text, flags=re.S)
    for span in fences + re.findall(r"`([^`]+)`", text):
        words.update(w.lower() for w in re.findall(r"/?([A-Za-z][A-Za-z0-9]*)", span))
        words.update(sym for sym in ("<<<", ">>>", "$", "%", "=", ";", "*", "+", "-", ".", "/") if sym in span)
    mentions[f] = words

rows_k, rows_o = [], []
for fn in sorted(os.listdir(hroot)):
    if not (fn.startswith("keyword_") or fn.startswith("ok_")) or not fn.endswith(".html"):
        continue
    pid = fn[:-5]
    name = title_of(pid)
    sym = re.match(r"^([^A-Za-z0-9 ]+) \(", name)
    key = sym.group(1) if sym else re.sub(r"[^a-z0-9]", "", re.sub(r"\(.*?\)|Keywords?$", "", name).lower())
    shortcut, desc = describe(page_text(pid))
    pages = [f[:-3] for f, ws in mentions.items() if key in ws][:3]
    plugin = ""
    if key in refused:
        plugin = "refused"
    elif key in noconf:
        plugin = "adds /NoConfirmation"
    row = f"| `{name}` | {('`' + shortcut + '`') if shortcut else ''} | `{pid}` | {', '.join(pages)} | {plugin} |"
    (rows_o if pid.startswith("ok_") else rows_k).append(row)

out = [
    "# Command keywords: index",
    "",
    f"Generated by `tools/atlas/keywords.py` from the MA help {ver} keyword pages and the plugin's",
    "command rules in `src/tools/generic.lua`. Do not edit by hand; rerun the script.",
    "",
    "- **Help page**: MA's text stays local (public repo); read it with",
    "  `python3 tools/helpsite/text.py <help page>` after `tools/helpsite/fetch.py`.",
    "- **Shortcut**: as the keyword page documents it. MA warns shortcuts change as keywords are added;",
    "  the plugin refuses a word that is a refused keyword, a documented alias, or a long-enough prefix.",
    "- **Topic pages**: studied pages that mention the keyword in code (open the page for the facts).",
    "- **Plugin**: how `ma3_command` treats a command that starts with it.",
    "- General rules (Command Syntax > Syntax Rules): every object has a default function and most",
    "  functions a default object; a function an object does not support is passed to a child or",
    "  parent object; values in quotes are case-sensitive, keywords are not; `( ... )` outside quotes",
    "  opens a text-input pop-up (refused by the plugin); `;` separates commands.",
    "",
    f"## Command keywords ({len(rows_k)})",
    "",
    "| Keyword | Shortcut | Help page | Topic pages | Plugin |",
    "| --- | --- | --- | --- | --- |",
    *rows_k,
    "",
    f"## Option keywords ({len(rows_o)})",
    "",
    "| Option | Shortcut | Help page | Topic pages | Plugin |",
    "| --- | --- | --- | --- | --- |",
    *rows_o,
    "",
]
open(os.path.join(topics, "keywords.md"), "w", encoding="utf-8").write("\n".join(out))
print(f"wrote docs/atlas/topics/keywords.md: {len(rows_k)} keywords, {len(rows_o)} options, "
      f"{sum(1 for r in rows_k if r.endswith('| refused |'))} refused")
